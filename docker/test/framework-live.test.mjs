import assert from 'node:assert/strict';
const base = process.env.APP_URL;
const login = await fetch(new URL('/api/login', base), { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: process.env.ADMIN_EMAIL, password: process.env.ADMIN_PASSWORD }) });
assert.equal(login.status, 200);
const cookie = login.headers.getSetCookie().map(value => value.split(';')[0]).join('; ');
assert(cookie);
const search = await fetch(new URL('/api/file/search', base), { method: 'POST', headers: { cookie, 'content-type': 'application/json' }, body: JSON.stringify({ take: 1, contentType: 'image', thumbnailStatus: 'Processed', returnThumbnails: false }) });
assert.equal(search.status, 200);
const data = await search.json();
assert(data.data?.length);
const thumbnail = new URL('/api/file/thumbnail/' + data.data[0].id + '/200', base);
assert.equal((await fetch(thumbnail)).status, 403);
const image = await fetch(thumbnail, { headers: { cookie } });
assert.equal(image.status, 200);
assert.match(image.headers.get('content-type'), /^image\//);
assert.match(image.headers.get('cache-control'), /max-age=3600/);
assert((await image.arrayBuffer()).byteLength > 0);
const optimized = await fetch(new URL('/_next/image?url=%2Fglobus.png&w=32&q=75', base));
assert.equal(optimized.status, 200);
assert.match(optimized.headers.get('content-type'), /^image\//);
assert.equal((await fetch(new URL('/_next/image?url=%2Fglobus.png&w=32&q=1', base))).status, 400);
console.log('Authenticated thumbnail delivery/cache and default optimized-image quality passed');
